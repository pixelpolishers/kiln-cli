// Package integration generates the files a build system needs to use the
// installed packages.
package integration

import (
	"fmt"
	"path/filepath"
	"sort"
	"strings"

	"github.com/pixelpolishers/kiln-core/manifest"
)

// Installed is a package unpacked on disk.
type Installed struct {
	Info manifest.PackageInfo
	Root string // absolute path of the package root
}

// CMakeTarget is the imported target name of a package target: "vendor::target".
func CMakeTarget(pkg, target string) string {
	vendor, _, _ := strings.Cut(pkg, "/")
	return vendor + "::" + target
}

// CMake renders kiln.cmake: imported targets for every installed package.
// Packages must be given dependencies first, although CMake itself resolves
// target references lazily.
func CMake(pkgs []Installed) (string, error) {
	byName := map[string]Installed{}
	for _, p := range pkgs {
		byName[p.Info.Name] = p
	}

	var b strings.Builder
	b.WriteString("# Generated by kiln. Do not edit; run `kiln install` to regenerate.\n")
	b.WriteString("# Use:  include(vendor/kiln/kiln.cmake)\n")
	b.WriteString("#       target_link_libraries(app PRIVATE vendor::target)\n\n")

	if len(pkgs) > 0 {
		// Packages that ship their own CMake config files (Qt6, absl, protobuf) can also be
		// used with find_package(); their install roots are searched.
		b.WriteString("list(APPEND CMAKE_PREFIX_PATH")
		for _, p := range pkgs {
			fmt.Fprintf(&b, "\n  \"%s\"", cmakePath(p.Root))
		}
		b.WriteString(")\n\n")
	}

	for _, p := range pkgs {
		names := make([]string, 0, len(p.Info.Targets))
		for n := range p.Info.Targets {
			names = append(names, n)
		}
		sort.Strings(names)
		fmt.Fprintf(&b, "# %s %s\n", p.Info.Name, p.Info.Version)
		for _, n := range names {
			t := p.Info.Targets[n]
			cm := CMakeTarget(p.Info.Name, n)
			var links []string
			for _, u := range t.Uses {
				if _, ok := p.Info.Targets[u]; !ok {
					return "", fmt.Errorf("%s: target %s uses unknown sibling target %q", p.Info.Name, n, u)
				}
				links = append(links, CMakeTarget(p.Info.Name, u))
			}
			for _, r := range t.Requires {
				dep, ok := byName[r.Package]
				if !ok {
					return "", fmt.Errorf("%s: target %s requires %s, which is not installed", p.Info.Name, n, r.Package)
				}
				wanted := r.Targets
				if len(wanted) == 0 {
					for dn := range dep.Info.Targets {
						wanted = append(wanted, dn)
					}
					sort.Strings(wanted)
				}
				for _, dn := range wanted {
					if _, ok := dep.Info.Targets[dn]; !ok {
						return "", fmt.Errorf("%s: target %s requires %s:%s, which has no such target", p.Info.Name, n, r.Package, dn)
					}
					links = append(links, CMakeTarget(r.Package, dn))
				}
			}
			links = append(links, t.Links...)

			var includes []string
			for _, inc := range t.Include {
				includes = append(includes, cmakePath(filepath.Join(p.Root, filepath.FromSlash(inc))))
			}
			var defines []string
			dnames := make([]string, 0, len(t.Defines))
			for k := range t.Defines {
				dnames = append(dnames, k)
			}
			sort.Strings(dnames)
			for _, k := range dnames {
				switch v := t.Defines[k].(type) {
				case nil:
					defines = append(defines, k)
				case bool:
					if v {
						defines = append(defines, k)
					}
				default:
					defines = append(defines, fmt.Sprintf("%s=%v", k, v))
				}
			}

			switch t.Type {
			case "header-only":
				fmt.Fprintf(&b, "if(NOT TARGET %s)\n  add_library(%s INTERFACE IMPORTED)\n", cm, cm)
				prop(&b, cm, "INTERFACE_INCLUDE_DIRECTORIES", includes)
				prop(&b, cm, "INTERFACE_COMPILE_DEFINITIONS", defines)
				prop(&b, cm, "INTERFACE_LINK_LIBRARIES", links)
				b.WriteString("endif()\n")
			case "library", "static-library", "dynamic-library":
				if len(t.Libs) == 0 {
					return "", fmt.Errorf("%s: library target %s lists no library files", p.Info.Name, n)
				}
				loc := cmakePath(filepath.Join(p.Root, filepath.FromSlash(t.Libs[0])))
				fmt.Fprintf(&b, "if(NOT TARGET %s)\n  add_library(%s UNKNOWN IMPORTED)\n", cm, cm)
				fmt.Fprintf(&b, "  set_target_properties(%s PROPERTIES IMPORTED_LOCATION \"%s\")\n", cm, loc)
				prop(&b, cm, "INTERFACE_INCLUDE_DIRECTORIES", includes)
				prop(&b, cm, "INTERFACE_COMPILE_DEFINITIONS", defines)
				prop(&b, cm, "INTERFACE_LINK_LIBRARIES", links)
				b.WriteString("endif()\n")
			case "executable":
				// a program that runs on the build machine (protoc, a code generator)
				if t.Exe == "" {
					return "", fmt.Errorf("%s: executable target %s lists no program file", p.Info.Name, n)
				}
				loc := cmakePath(filepath.Join(p.Root, filepath.FromSlash(t.Exe)))
				fmt.Fprintf(&b, "if(NOT TARGET %s)\n  add_executable(%s IMPORTED)\n", cm, cm)
				fmt.Fprintf(&b, "  set_target_properties(%s PROPERTIES IMPORTED_LOCATION \"%s\")\n", cm, loc)
				b.WriteString("endif()\n")
			default:
				// modules are not linked against
				fmt.Fprintf(&b, "# %s (%s): not linkable\n", cm, t.Type)
			}
		}
		b.WriteString("\n")
	}
	return b.String(), nil
}

func prop(b *strings.Builder, target, name string, values []string) {
	if len(values) == 0 {
		return
	}
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = v
	}
	fmt.Fprintf(b, "  set_target_properties(%s PROPERTIES %s \"%s\")\n", target, name, strings.Join(quoted, ";"))
}

func cmakePath(p string) string { return filepath.ToSlash(p) }
